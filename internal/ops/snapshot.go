package ops

import (
	"context"
	"fmt"
	"io"
	"net/url"
	"sort"
	"strings"

	"github.com/carlosprados/openproject-cli/internal/hal"
)

func init() { register(projSnapshot) }

// snapshot is the project tree as a deterministic document: the same server
// state always gives the same bytes, so a caller can diff or commit it.
type snapshot struct {
	Root     string            `json:"root"`
	Projects []snapshotProject `json:"projects"`
}

type snapshotProject struct {
	ID                int               `json:"id"`
	Identifier        string            `json:"identifier"`
	Name              string            `json:"name"`
	Path              []string          `json:"path"`
	Parent            string            `json:"parent,omitempty"`
	ParentID          int               `json:"parentId,omitempty"`
	Status            string            `json:"status,omitempty"`
	StatusExplanation string            `json:"statusExplanation,omitempty"`
	Description       string            `json:"description,omitempty"`
	Active            bool              `json:"active"`
	Public            bool              `json:"public"`
	CreatedAt         string            `json:"createdAt,omitempty"`
	UpdatedAt         string            `json:"updatedAt,omitempty"`
	URL               string            `json:"url"`
	Versions          []snapshotVersion `json:"versions"`
}

type snapshotVersion struct {
	ID          int    `json:"id"`
	Name        string `json:"name"`
	Status      string `json:"status"`
	StartDate   string `json:"startDate,omitempty"`
	EndDate     string `json:"endDate,omitempty"`
	Sharing     string `json:"sharing"`
	Description string `json:"description,omitempty"`
	CreatedAt   string `json:"createdAt,omitempty"`
	UpdatedAt   string `json:"updatedAt,omitempty"`
}

var projSnapshot = &Op{
	Cmd:   []string{"project", "snapshot"},
	Short: "The project tree (project, subprojects, versions) as deterministic JSON",
	Long: `Read a project, every subproject below it and the versions each one
defines, as one JSON document: projects sorted by id, each with its path of
identifiers from the root, its parent and its versions (sorted by id; a
shared version appears only under the project that defines it). Nothing in
it is generated by opcli (no timestamps of its own), so the same server state
always gives the same output: diff it or commit it to see what changed.
Work packages are not included: export them with 'opcli wp export'.`,
	Example: `  opcli project snapshot demo-project -o json > tree.json
  opcli project snapshot demo-project -o json | jq -r '.projects[] | "\(.path | join("/")) \(.versions | length)"'
  opcli project snapshot demo-project            # indented tree for humans`,
	Params: []Param{pProjectArg()},
	Text:   renderSnapshot,
	Run: func(ctx context.Context, e *Env, a Args) (any, error) {
		pid, err := e.ProjectID(ctx, a.String("project"))
		if err != nil {
			return nil, err
		}
		root, err := e.C.Get(ctx, fmt.Sprintf("/projects/%d", pid), nil)
		if err != nil {
			return nil, err
		}
		f := NewFilters().Add("ancestor", "=", pid)
		below, _, err := e.C.Collect(ctx, "/projects", url.Values{"filters": {f.JSON()}}, 0)
		if err != nil {
			return nil, err
		}
		snap, skipped := buildSnapshot(pid, hal.FlattenAll(append([]map[string]any{root}, below...)),
			func(ident string) string { return e.C.WebURL("/projects/" + ident) })
		if len(skipped) > 0 {
			e.warnf("left out %s: the server lists them below %s but their parent chain does not reach it", strings.Join(skipped, ", "), snap.Root)
		}
		for i := range snap.Projects {
			p := &snap.Projects[i]
			items, _, err := e.C.Collect(ctx, fmt.Sprintf("/projects/%d/versions", p.ID), nil, 0)
			if err != nil {
				return nil, err
			}
			for _, v := range hal.FlattenAll(items) {
				if intOf(v["definingProjectId"]) == p.ID {
					p.Versions = append(p.Versions, snapshotVersionOf(v))
				}
			}
			sort.Slice(p.Versions, func(i, j int) bool { return p.Versions[i].ID < p.Versions[j].ID })
		}
		return snap, nil
	},
}

func snapshotVersionOf(v map[string]any) snapshotVersion {
	return snapshotVersion{
		ID: intOf(v["id"]), Name: strOf(v["name"]), Status: strOf(v["status"]),
		StartDate: strOf(v["startDate"]), EndDate: strOf(v["endDate"]), Sharing: strOf(v["sharing"]),
		Description: strOf(v["description"]), CreatedAt: strOf(v["createdAt"]), UpdatedAt: strOf(v["updatedAt"]),
	}
}

// buildSnapshot keeps the projects whose parent chain reaches the root
// (projectTree), sorted by id, each with its path of identifiers from the
// root. The rest are returned as skipped.
func buildSnapshot(rootID int, projects []map[string]any, webURL func(string) string) (*snapshot, []string) {
	paths, skipped := projectTree(rootID, projects)
	s := &snapshot{Projects: []snapshotProject{}}
	for _, p := range projects {
		id := intOf(p["id"])
		path, ok := paths[id]
		if !ok {
			continue
		}
		sp := snapshotProject{
			ID: id, Identifier: strOf(p["identifier"]), Name: strOf(p["name"]), Path: path,
			Status: strOf(p["status"]), StatusExplanation: strOf(p["statusExplanation"]), Description: strOf(p["description"]),
			Active: p["active"] == true, Public: p["public"] == true,
			CreatedAt: strOf(p["createdAt"]), UpdatedAt: strOf(p["updatedAt"]),
			URL: webURL(strOf(p["identifier"])), Versions: []snapshotVersion{},
		}
		if id == rootID {
			s.Root = sp.Identifier
		} else {
			sp.Parent, sp.ParentID = strOf(p["parent"]), intOf(p["parentId"])
		}
		s.Projects = append(s.Projects, sp)
	}
	sort.Slice(s.Projects, func(i, j int) bool { return s.Projects[i].ID < s.Projects[j].ID })
	return s, skipped
}

func renderSnapshot(w io.Writer, v any) error {
	s, ok := v.(*snapshot)
	if !ok {
		return RenderJSON(w, v)
	}
	ps := append([]snapshotProject(nil), s.Projects...)
	sort.SliceStable(ps, func(i, j int) bool { return strings.Join(ps[i].Path, "/") < strings.Join(ps[j].Path, "/") })
	for _, p := range ps {
		indent := strings.Repeat("  ", max(len(p.Path)-1, 0))
		status := ""
		if p.Status != "" {
			status = " [" + p.Status + "]"
		}
		fmt.Fprintf(w, "%s%s  %s%s\n", indent, p.Identifier, p.Name, status)
		for _, ver := range p.Versions {
			dates := ""
			if ver.StartDate != "" || ver.EndDate != "" {
				dates = fmt.Sprintf("  %s → %s", orDash(ver.StartDate), orDash(ver.EndDate))
			}
			fmt.Fprintf(w, "%s  · %s (%s, %s)%s\n", indent, ver.Name, ver.Status, ver.Sharing, dates)
		}
	}
	return nil
}

func orDash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}

// strOf returns v when it is a string and "" otherwise (nil, absent).
func strOf(v any) string {
	s, _ := v.(string)
	return s
}
